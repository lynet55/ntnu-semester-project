"""Write figures/dce-curve.tex: validation RMSE of the depth encoder per epoch (TikZ, bb_theme).

Reads the training logs of uuv-rl-env (worktree "environment"), keeps every 5th epoch, and writes
plain TikZ coordinates (no pgfplots needed). Standard library only:

    python3 scripts/make_dce_curve.py [<uuv-rl-env logs dir>]

Runs: dce_D001 (25888723, cube, epochs 1-100) + dce_D001_resume (25888960, epochs 101-250),
and dce_D001_box (25903576, box, epochs 1-250).
"""
import os
import re
import sys

LOGS = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/uuv-sim/uuv-rl-env-environment/experiments/logs")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "figures", "dce-curve.tex")


def rows(job):
    out = []
    for line in open(os.path.join(LOGS, f"dce_train_{job}.out")):
        m = re.match(r"epoch (\d+) .*?val/rmse_m ([\d.]+)", line)
        if m:
            out.append((int(m.group(1)), float(m.group(2))))
    return out


def coords(rs):
    # x: 0.04 cm per epoch; y: 5 cm per metre, from 0.4 m
    return " ".join(f"({e * 0.04:.2f},{(v - 0.4) * 5:.3f})" for e, v in rs if e == 1 or e % 5 == 0)


cube = rows("25888723") + [r for r in rows("25888960") if r[0] > 100]
box = rows("25903576")

TEX = r"""% !TEX root = ../main.tex
% Validation RMSE of the depth encoder (DCE) per epoch, bb_theme palette.
% GENERATED by scripts/make_dce_curve.py from the uuv-rl-env training logs; do not edit by hand.
% x: 0.04 cm per epoch; y: 5 cm per metre, from 0.4 m.
% Use inside a figure environment:  \input{figures/dce-curve.tex}
\definecolor{vaeInk}{HTML}{0F1B2D}
\definecolor{vaeSignal}{HTML}{1D5FD1}
\definecolor{vaeMuted}{HTML}{56677F}
\definecolor{vaeHatch}{HTML}{2F3FD0}
\begin{tikzpicture}[font=\footnotesize, line cap=round, line join=round]
  % grid and axes
  \foreach \y/\l in {0.5/0.5, 1/0.6, 2/0.8, 3/1.0, 4/1.2, 5/1.4} {
    \draw[vaeMuted!25, line width=0.3pt] (0,\y) -- (10,\y);
    \node[anchor=east, text=vaeMuted] at (-0.08,\y) {\l};
  }
  \foreach \x/\l in {0/0, 2/50, 4/100, 6/150, 8/200, 10/250} {
    \draw[vaeInk, line width=0.5pt] (\x,0) -- (\x,-0.08);
    \node[anchor=north, text=vaeMuted] at (\x,-0.1) {\l};
  }
  \draw[vaeInk, line width=0.6pt] (0,0) -- (10,0);
  \draw[vaeInk, line width=0.6pt] (0,0) -- (0,5.2);
  \node[anchor=north] at (5,-0.55) {Epoch};
  \node[rotate=90, anchor=south] at (-0.75,2.6) {Validation RMSE (m)};
  % resume of the cube run
  \draw[vaeMuted, line width=0.4pt, dash pattern=on 2pt off 1.5pt] (4,0) -- (4,5.2);
  \node[anchor=north west, text=vaeMuted, font=\scriptsize, align=left] at (4.05,5.15) {cube run resumed,\\learning rate restarted};
  % curves
  \draw[vaeMuted, line width=0.9pt, dash pattern=on 3pt off 2pt] plot coordinates {CUBE};
  \draw[vaeSignal, line width=0.9pt] plot coordinates {BOX};
  % legend
  \draw[vaeSignal, line width=0.9pt] (7.0,3.2) -- (7.5,3.2) node[anchor=west, text=vaeInk] {box target (final)};
  \draw[vaeMuted, line width=0.9pt, dash pattern=on 3pt off 2pt] (7.0,2.8) -- (7.5,2.8) node[anchor=west, text=vaeInk] {cube target};
\end{tikzpicture}
"""

with open(OUT, "w") as f:
    f.write(TEX.replace("CUBE", coords(cube)).replace("BOX", coords(box)))
print(f"wrote {os.path.normpath(OUT)}: cube {len(cube)} epochs, box {len(box)} epochs")
